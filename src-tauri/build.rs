//! Generates the app-command permission sets from the commands registered in
//! `src/lib.rs`, so the capability files can never drift from the code:
//! - `operator-commands`: every command (operator console window)
//! - `projector-commands`: only what the projector output window needs

use std::fmt::Write as _;

const PROJECTOR_COMMANDS: &[&str] = &["presentation_get_state", "projector_report"];

fn registered_commands() -> Vec<String> {
    let lib = std::fs::read_to_string("src/lib.rs").expect("read src/lib.rs");
    let start = lib.find("generate_handler![").expect("generate_handler! in lib.rs") + "generate_handler![".len();
    let end = start + lib[start..].find(']').expect("end of generate_handler!");
    lib[start..end]
        .split(',')
        .map(|s| s.trim())
        .filter(|s| !s.is_empty())
        .map(|s| s.rsplit("::").next().unwrap_or(s).to_string())
        .collect()
}

fn permission_set(identifier: &str, description: &str, commands: &[String]) -> String {
    let mut out = String::from("# Generated by build.rs from the commands registered in src/lib.rs. Do not edit.\n\n");
    writeln!(out, "[[set]]\nidentifier = \"{identifier}\"\ndescription = \"{description}\"\npermissions = [").unwrap();
    for c in commands {
        writeln!(out, "  \"allow-{}\",", c.replace('_', "-")).unwrap();
    }
    out.push_str("]\n");
    out
}

fn write_if_changed(path: &str, content: &str) {
    if std::fs::read_to_string(path).ok().as_deref() != Some(content) {
        std::fs::write(path, content).expect("write permission set");
    }
}

fn main() {
    // Declaring any rerun-if-changed path makes Cargo watch only those paths,
    // so the icons (embedded in the .exe by tauri-build) must be listed too.
    println!("cargo:rerun-if-changed=src/lib.rs");
    println!("cargo:rerun-if-changed=icons");
    let commands = registered_commands();
    for p in PROJECTOR_COMMANDS {
        assert!(commands.iter().any(|c| c == p), "projector command {p} is not registered");
    }
    let projector: Vec<String> = PROJECTOR_COMMANDS.iter().map(|s| s.to_string()).collect();
    std::fs::create_dir_all("permissions").expect("create permissions dir");
    write_if_changed(
        "permissions/operator-commands.toml",
        &permission_set("operator-commands", "All SanctuaryFlow commands, for the operator console.", &commands),
    );
    write_if_changed(
        "permissions/projector-commands.toml",
        &permission_set("projector-commands", "Read-only presentation access for the projector output window.", &projector),
    );

    // The manifest needs 'static names; leaking in a build script is harmless.
    let names: &'static [&'static str] =
        Box::leak(commands.into_iter().map(|c| &*Box::leak(c.into_boxed_str())).collect::<Vec<_>>().into_boxed_slice());
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(tauri_build::AppManifest::new().commands(names)))
        .expect("failed to run tauri-build");
}
